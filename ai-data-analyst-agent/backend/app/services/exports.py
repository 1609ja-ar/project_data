def powerbi_package(frame: pd.DataFrame, schema: list[dict], parquet_path, version: dict, dataset: dict) -> bytes:
    roles = detect_roles(schema, dataset.get("column_roles"))
    dictionary = pd.DataFrame([{
        "column_key": c["key"], "display_name": c["display_name"], "detected_type": c["dtype"],
        "meaning": c["semantic_type"], "powerbi_type": powerbi_type(c)[1], "missing_count": c["missing"]} for c in schema])
    table = pq.read_table(parquet_path, columns=[c["key"] for c in schema])
    pbuf = io.BytesIO()
    pq.write_table(table, pbuf, compression="zstd")
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("data.csv", frames.to_csv_bytes(frame, schema))
        z.writestr("data.parquet", pbuf.getvalue())
        z.writestr("data_dictionary.csv", dictionary.to_csv(index=False, lineterminator="\n"))
        z.writestr("Load.pq", m_script(schema))
        z.writestr("measures.dax", dax_measures(schema, roles))
        z.writestr("README_PowerBI.md", README_PBI.format(version=version["version_number"]))
    return buf.getvalue()


# ------------------------------------------------------------------ Excel workbook

def _cell(ws, value, *, text=False, fmt=None, bold=False):
    c = WriteOnlyCell(ws, value=value)
    if text and isinstance(value, str):
        c.data_type = "s"  # never a formula, even if it starts with =, +, -, @
    if fmt:
        c.number_format = fmt
    if bold:
        c.font = Font(bold=True)
        c.fill = PatternFill("solid", fgColor="EEF2FF")
    return c


def _excel_values(frame: pd.DataFrame, c: dict) -> list:
    s = frame[c["key"]]
    if c["dtype"] == "decimal":
        return [None if pd.isna(t) else Decimal(t) for t in minor_to_text(s, c.get("scale", 2))]
    if c["dtype"] == "integer":
        return [None if pd.isna(v) else int(v) for v in s]
    if c["dtype"] == "float":
        return [None if pd.isna(v) else float(v) for v in s]
    if c["dtype"] in ("date", "datetime"):
        return [None if pd.isna(v) else v.to_pydatetime() for v in s]
    if c["dtype"] == "boolean":
        return [None if pd.isna(v) else bool(v) for v in s]
    return [None if pd.isna(v) else str(v) for v in s]


def _fmt(c: dict) -> str | None:
    if c["dtype"] == "decimal":
        return money_format(c, "#,##0." + "0" * c.get("scale", 2))
    if c["semantic_type"] == "percent":
        return "0.00%"
    return {"date": "yyyy-mm-dd", "datetime": "yyyy-mm-dd hh:mm:ss", "integer": "0"}.get(c["dtype"])


def _summary_sheet(wb, summary: dict, dataset: dict, version: dict) -> None:
    """KPIs and the view description at the front of the workbook. Values are copied from verified results."""
    ws = wb.create_sheet("Summary")
    ws.column_dimensions["A"].width = 38
    ws.column_dimensions["B"].width = 22
    ws.column_dimensions["C"].width = 16
    ws.column_dimensions["D"].width = 26
    ws.append([_cell(ws, summary.get("title") or f"{dataset['filename']} export", text=True, bold=True)])
    ws.append([_cell(ws, "Dataset", text=True), _cell(ws, dataset["filename"], text=True)])
    ws.append([_cell(ws, "Version", text=True), version["version_number"]])
    ws.append([_cell(ws, "Exported", text=True), _cell(ws, datetime.now().strftime("%Y-%m-%d %H:%M"), text=True)])
    ws.append([_cell(ws, "Rows exported", text=True), summary.get("rows")])
    ws.append([_cell(ws, "Filters", text=True), _cell(ws, "; ".join(summary.get("filters") or []) or "None", text=True)])
    ws.append([])
    if summary.get("kpis"):
        ws.append([_cell(ws, h, text=True, bold=True) for h in ("Measure", "Value", "Change", "Compared periods")])
        for k in summary["kpis"]:
            col = k.get("column") or {}
            fmt = (money_format(col, "#,##0.00") if col.get("semantic_type") == "currency"
                   else "0.00%" if col.get("semantic_type") == "percent" else "#,##0" if col.get("dtype") == "integer" else "#,##0.00")
            ch = k.get("change")
            ws.append([_cell(ws, k["label"], text=True), _cell(ws, k["value"], fmt=fmt),
                       _cell(ws, ch["pct"], fmt="+0.0%;-0.0%;0.0%") if ch else None,
                       _cell(ws, f"{ch['period']} vs {ch['previous_period']}", text=True) if ch else None])
    ws.append([])
    ws.append([_cell(ws, "All figures are computed by the app and verified by a second engine; charts are on the Charts sheet.", text=True)])


def excel_workbook(frame: pd.DataFrame, schema: list[dict], version: dict, dataset: dict, charts: list[dict] | None = None,
                   summary: dict | None = None, include: set[str] | None = None) -> tuple[bytes, list[str]]:
    """include: optional subset of {"dictionary", "cleaning"} (default both). summary adds a front sheet."""
    include = {"dictionary", "cleaning"} if include is None else include
    wb = Workbook(write_only=True)
    if summary:
        _summary_sheet(wb, summary, dataset, version)
    ws = wb.create_sheet("Data")
    ws.freeze_panes = "A2"
    n = len(frame)
    if schema:
        ws.auto_filter.ref = f"A1:{get_column_letter(len(schema))}{max(1, n + 1)}"
    for i, c in enumerate(schema, start=1):
        ws.column_dimensions[get_column_letter(i)].width = min(40, max(10, len(c["display_name"]) + 2))
    ws.append([_cell(ws, c["display_name"], text=True, bold=True) for c in schema])
    cols = [_excel_values(frame, c) for c in schema]
    fmts = [_fmt(c) for c in schema]
    is_text = [c["dtype"] == "string" for c in schema]
    for r in range(n):
        ws.append([_cell(ws, cols[j][r], text=is_text[j], fmt=fmts[j]) if cols[j][r] is not None else None for j in range(len(schema))])

    if "dictionary" in include:
        dd = wb.create_sheet("Data dictionary")
        head = ["Column", "Key", "Type", "Meaning", "Empty values", "Distinct values", "Examples"]
        dd.append([_cell(dd, h, text=True, bold=True) for h in head])
        for c in schema:
            dd.append([_cell(dd, c["display_name"], text=True), _cell(dd, c["key"], text=True), c["dtype"], c["semantic_type"],
                       c["missing"], c["unique"], _cell(dd, ", ".join((c.get("profile") or {}).get("examples", [])), text=True)])

    if "cleaning" in include:
        rep = wb.create_sheet("Cleaning report")
        report = version.get("cleaning_report") or {}
        rep.append([_cell(rep, "Dataset", text=True, bold=True), _cell(rep, dataset["filename"], text=True)])
        rep.append([_cell(rep, "Version", text=True, bold=True), version["version_number"]])
        rep.append([_cell(rep, "Exported", text=True, bold=True), _cell(rep, datetime.now().strftime("%Y-%m-%d %H:%M"), text=True)])
        for k, v in (report.get("summary") or {}).items():
            if not isinstance(v, (list, dict)):
                rep.append([_cell(rep, k.replace("_", " "), text=True, bold=True), v])
        rep.append([])
        rep.append([_cell(rep, h, text=True, bold=True) for h in ("Step", "Column", "Rows affected", "Severity", "Description", "Examples")])
        for s in report.get("steps", []):
            rep.append([_cell(rep, s["step"], text=True), _cell(rep, s.get("column") or "", text=True), s["rows_affected"],
                        _cell(rep, s["severity"], text=True), _cell(rep, s["description"], text=True),
                        _cell(rep, " | ".join(s.get("examples") or []), text=True)])

    skipped = []
    if charts:
        agg = wb.create_sheet("Aggregates")
        cs = wb.create_sheet("Charts")
        row = 1
        anchor_row = 1
        for ch in charts:
            spec, columns, rows = ch["chart"], ch["columns"], ch["rows"]
            if spec.get("type") == "donut":
                spec = {**spec, "type": "pie"}
            if spec.get("type") not in NATIVE_CHARTS or not rows:
                skipped.append(ch.get("title") or spec.get("type"))
                continue
            idx = {c["key"]: i for i, c in enumerate(columns)}
            if spec.get("x") not in idx or spec.get("y") not in idx:
                skipped.append(ch.get("title") or spec.get("type"))
                continue
            # Pivot backend rows (x, [series], value) into a block of cells; values are copied, not recomputed.
            xs, series = [], []
            vals: dict = {}
            for r in rows:
                x = "(empty)" if r[idx[spec["x"]]] is None else str(r[idx[spec["x"]]])
                s_name = (("(empty)" if r[idx[spec["series"]]] is None else str(r[idx[spec["series"]]]))
                          if spec.get("series") in idx else columns[idx[spec["y"]]]["label"])
                if x not in xs:
                    xs.append(x)
                if s_name not in series:
                    series.append(s_name)
                vals[(x, s_name)] = r[idx[spec["y"]]]
            top = row
            agg.append([_cell(agg, ch.get("title") or "Chart", text=True, bold=True)])
            agg.append([_cell(agg, columns[idx[spec["x"]]]["label"], text=True, bold=True)] + [_cell(agg, s, text=True, bold=True) for s in series])
            for x in xs:
                agg.append([_cell(agg, x, text=True)] + [vals.get((x, s)) for s in series])
            agg.append([])
            header_row, first_data, last_data = top + 1, top + 2, top + 1 + len(xs)
            row = last_data + 2
            t = spec["type"]
            chart = (LineChart() if t == "line" else AreaChart() if t == "area" else PieChart() if t == "pie" else BarChart())
            if isinstance(chart, BarChart):
                chart.type = "bar" if t == "horizontal_bar" else "col"
                if t in ("stacked_bar", "stacked_100_bar"):
                    chart.grouping = "percentStacked" if t == "stacked_100_bar" else "stacked"
                    chart.overlap = 100
            chart.title = ch.get("title") or columns[idx[spec["y"]]]["label"]
            data_ref = Reference(agg, min_col=2, max_col=1 + len(series), min_row=header_row, max_row=last_data)
            cats = Reference(agg, min_col=1, min_row=first_data, max_row=last_data)
            chart.add_data(data_ref, titles_from_data=True)
            chart.set_categories(cats)
            chart.width, chart.height = 18, 9
            cs.add_chart(chart, f"A{anchor_row}")
            anchor_row += 20
    out = io.BytesIO()
    wb.save(out)
    return out.getvalue(), skipped


def sql_result_workbook(columns: list[dict], rows: list[list], sql: str) -> bytes:
    wb = Workbook(write_only=True)
    ws = wb.create_sheet("Result")
    ws.freeze_panes = "A2"
    ws.append([_cell(ws, c["label"], text=True, bold=True) for c in columns])
    fmt = {"date": "yyyy-mm-dd", "datetime": "yyyy-mm-dd hh:mm:ss"}
    for r in rows:
        out = []
        for v, c in zip(r, columns):
            if v is None:
                out.append(None)
            elif c["dtype"] in ("date", "datetime") and isinstance(v, str):
                out.append(_cell(ws, pd.Timestamp(v).to_pydatetime(), fmt=fmt[c["dtype"]]))
            elif c["dtype"] == "decimal":
                out.append(Decimal(str(v)))
            else:
                out.append(_cell(ws, v, text=c["dtype"] == "string"))
        ws.append(out)
    q = wb.create_sheet("Query")
    q.append([_cell(q, "SQL that ran", text=True, bold=True)])
    q.append([_cell(q, sql, text=True)])
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
