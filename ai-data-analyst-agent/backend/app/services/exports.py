CURRENCY_FORMATS = {"USD": '"$"#,##0.00', "EUR": '"€"#,##0.00', "GBP": '"£"#,##0.00', "INR": '"₹"#,##0.00', "JPY": '"¥"#,##0'}


def money_format(col: dict, fallback: str) -> str:
    """Excel format for a money column: its own currency, or the default (INR) when none was recorded.
    `#,##0` follows the computer's digit grouping, so Excel set to Indian grouping shows 12,34,567.50."""
    if col.get("semantic_type") != "currency":
        return CURRENCY_FORMATS.get(col.get("currency") or "", fallback)
    return CURRENCY_FORMATS.get((col.get("currency") or default_currency()).upper(), fallback)
FORMULA_PREFIXES = ("=", "+", "-", "@")
NATIVE_CHARTS = {"bar", "horizontal_bar", "grouped_bar", "stacked_bar", "stacked_100_bar", "line", "area", "pie"}


# ------------------------------------------------------------------ escaping

def m_string(s: str) -> str:
    """Power Query M text literal."""
    return '"' + str(s).replace('"', '""') + '"'


def m_ident(s: str) -> str:
    """Power Query M quoted identifier: #"Column Name"."""
    return "#" + m_string(s)


def dax_table(t: str) -> str:
    return "'" + t.replace("'", "''") + "'"


def dax_col(table: str, col: str) -> str:
    return f"{dax_table(table)}[{col.replace(']', ']]')}]"


def powerbi_type(c: dict) -> tuple[str, str]:
    """(M type expression, human name)"""
    if c["dtype"] == "decimal":
        return ("Currency.Type", "Fixed decimal (currency)") if c.get("scale", 2) <= 4 else ("type number", "Decimal number")
    if c["semantic_type"] == "percent":
        return "Percentage.Type", "Percentage"
    return {"integer": ("Int64.Type", "Whole number"), "float": ("type number", "Decimal number"),
            "date": ("type date", "Date"), "datetime": ("type datetime", "Date/time"),
            "boolean": ("type logical", "True/false")}.get(c["dtype"], ("type text", "Text"))


# ------------------------------------------------------------------ Power BI package

def m_script(schema: list[dict]) -> str:
    types = ",\n        ".join(f"{{{m_string(c['display_name'])}, {powerbi_type(c)[0]}}}" for c in schema)
    first = schema[0]["display_name"] if schema else "Column1"
    return f"""// Power Query M script generated by AI Data Analyst Agent.
// 1. Set FilePath to where you saved data.csv.  2. Home > Transform data > Advanced Editor, paste, Done.
let
    FilePath = "C:\\Users\\you\\Downloads\\data.csv",
    Source = Csv.Document(File.Contents(FilePath), [Delimiter = ",", Columns = {len(schema)}, Encoding = 65001, QuoteStyle = QuoteStyle.Csv]),
    PromotedHeaders = Table.PromoteHeaders(Source, [PromoteAllScalars = true]),
    // The CSV uses '.' decimals and ISO dates, so types are applied with the en-US culture.
    ChangedTypes = Table.TransformColumnTypes(PromotedHeaders, {{
        {types}
    }}, "en-US"),
    // Example of referencing a column whose name has spaces or quotes: {m_ident(first)}
    Result = ChangedTypes
in
    Result
"""


def m_web_script(schema: list[dict], feed_url: str) -> str:
    """Power Query M that loads the live CSV feed (refreshable). The token goes in the request header."""
    types = ",\n        ".join(f"{{{m_string(c['display_name'])}, {powerbi_type(c)[0]}}}" for c in schema)
    return f"""// Live feed query generated by AI Data Analyst Agent. Refresh pulls the latest cleaned version.
// Replace PASTE_TOKEN_HERE with your export token (pbi_...). Keep this file private: it contains the token.
let
    FeedUrl = {m_string(feed_url)},
    Token = "PASTE_TOKEN_HERE",
    Source = Csv.Document(Web.Contents(FeedUrl, [Headers = [Authorization = "Bearer " & Token]]),
        [Delimiter = ",", Columns = {len(schema)}, Encoding = 65001, QuoteStyle = QuoteStyle.Csv]),
    PromotedHeaders = Table.PromoteHeaders(Source, [PromoteAllScalars = true]),
    ChangedTypes = Table.TransformColumnTypes(PromotedHeaders, {{
        {types}
    }}, "en-US")
in
    ChangedTypes
"""


def dax_measures(schema: list[dict], roles: dict, table: str = "data") -> str:
    by_key = {c["key"]: c for c in schema}
    lines = ["-- DAX measures generated by AI Data Analyst Agent. Table name: data.",
             "-- Add each one with Modeling > New measure. Only columns that exist in this dataset are used.", ""]
    lines += ["Row Count = COUNTROWS(" + dax_table(table) + ")", ""]
    rev = by_key.get(roles.get("revenue")) if roles.get("revenue") else None
    order = by_key.get(roles.get("order_id")) if roles.get("order_id") else None
    date = by_key.get(roles.get("date")) if roles.get("date") else None
    if rev:
        lines += [f"Total Revenue = SUM({dax_col(table, rev['display_name'])})", ""]
        if order:
            lines += [f"Order Count = DISTINCTCOUNT({dax_col(table, order['display_name'])})", "",
                      "Average Order Value = DIVIDE([Total Revenue], [Order Count])", ""]
        else:
            lines += ["-- No order ID column was found, so the average is per row.",
                      "Average per Row = DIVIDE([Total Revenue], [Row Count])", ""]
        if date:
            lines += [
                "-- Time intelligence needs a date table. Create DateTable (Modeling > New table), mark it as a date table,",
                f"-- and relate DateTable[Date] to {dax_col(table, date['display_name'])}.",
                f"DateTable = ADDCOLUMNS(CALENDAR(DATE(YEAR(MIN({dax_col(table, date['display_name'])})), 1, 1), "
                f"DATE(YEAR(MAX({dax_col(table, date['display_name'])})), 12, 31)), \"Year\", YEAR([Date]), "
                "\"Month\", FORMAT([Date], \"YYYY-MM\"), \"Quarter\", \"Q\" & QUARTER([Date]))", "",
                "-- Growth % = (current - previous) / |previous|; blank when previous is 0 or blank.",
                "Revenue MoM % =\nVAR Curr = [Total Revenue]\nVAR Prev = CALCULATE([Total Revenue], DATEADD('DateTable'[Date], -1, MONTH))\n"
                "RETURN DIVIDE(Curr - Prev, ABS(Prev))", "",
                "Revenue YoY % =\nVAR Curr = [Total Revenue]\nVAR Prev = CALCULATE([Total Revenue], SAMEPERIODLASTYEAR('DateTable'[Date]))\n"
                "RETURN DIVIDE(Curr - Prev, ABS(Prev))", ""]
    else:
        lines += ["-- No revenue-like column was detected; revenue, order value and growth measures were skipped.", ""]
        for c in schema:
            if c["dtype"] in ("integer", "float", "decimal") and c["semantic_type"] not in ("id", "percent"):
                lines += [f"Total {c['display_name'].replace(']', '')} = SUM({dax_col(table, c['display_name'])})", ""]
    return "\n".join(lines)


